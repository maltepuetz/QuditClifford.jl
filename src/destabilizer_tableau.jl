"""
    DestabilizerTableau(d::Int, n::Int; state::Symbol=:mixed, basis=:Z, storephase::Bool=true)
    DestabilizerTableau(d::Int, n::Int, state::Symbol; kwargs...)
    DestabilizerTableau(d::Int, tableau::AbstractMatrix{<:Integer}; m::Union{Int,Nothing}=nothing, storephase::Union{Bool,Nothing}=nothing)

Construct a destabilizer tableau for an `n`-qudit *stabilizer density operator*
(mixed-state stabilizer formalism).

This is the recommended tableau representation for most workflows. In addition
to the stabilizer generators, it maintains a dual destabilizer basis, enabling
fast span-membership tests, expectation values, and repeated measurements
without first canonicalizing the stabilizer generators.

# Arguments
- `d::Int`: Qudit dimension (must be a prime number).
- `n::Int`: Number of qudits (only for the `d, n` constructor).
- `state::Symbol`: Preset state for the positional `state` constructor.
- `tableau::AbstractMatrix{<:Integer}`: An integer stabilizer matrix in either
  `(2n + storephase) × m` or `m × (2n + storephase)` layout. The corresponding
  destabilizers are constructed automatically.

# Keyword Arguments
- `state::Symbol=:mixed`: Preset state (`:mixed`, `:product`, `:ghz`). Aliases
  `:X/:Y/:Z` map to `:product` in that basis.
- `basis=:Z`: Basis for product states (`:X`, `:Y`, `:Z`, or a per-qudit
  vector/tuple of Symbols).
- `storephase::Bool=true`: Whether to store the stabilizer phase row (for the
  `(d, n)` constructor). When constructing from a `tableau`, `storephase` is
  inferred from the matrix shape if not provided. Destabilizers never carry a
  phase row.
- `m::Union{Int,Nothing}=nothing`: Number of active stabilizer-generator columns
  (for the `(d, tableau)` constructor).
- `inversemod::InverseMod=PrecomputedInvMod(d)`: Inversion strategy used for
  phase calculations and construction of the dual basis.
- `check::Bool=true`: For the `(d, tableau)` constructor only, verify that the
  supplied generators commute and are independent, throwing `ArgumentError`
  naming the offending pair or the rank if they do not. The preset constructors
  satisfy both by construction and take no such keyword. `check=false` skips an
  `O(n^3)` validation and builds the tableau regardless -- every later operation
  then rests on a contract that may not hold, and `is_pure` will call such a
  tableau pure; `is_pure(tab; verify=true)` is what sees through it.

# Examples
```julia
tab = DestabilizerTableau(2, 3; state=:mixed)
tab = DestabilizerTableau(2, 3; state=:product, basis=:X)

raw = reshape(Int[0, 1, 0], 3, 1)
tab = DestabilizerTableau(2, raw)
```

# Notes
## Representation
The represented abelian stabilizer subgroup `S` is generated by `m` independent
commuting Paulis (`0 ≤ m ≤ n`). Both properties are contract: the raw-matrix
constructor enforces them (see `check`), the presets satisfy them by
construction, and `measure!` and [`canonicalize!`](@ref) preserve them. That is
what lets [`is_pure`](@ref) decide on `m == n` alone. Each active stabilizer `S_j` has a destabilizer
`D_j` satisfying the duality relation `⟨D_j, S_k⟩ = δ_jk` modulo `d`.

The internal stabilizer tableau has shape `(2n + storephase) × n`, while the
destabilizer matrix has shape `2n × n`.
- Only the **first `m` columns** are active stabilizer/destabilizer pairs.
- Columns `m+1:n` are unused (kept zero) and provide capacity for measurements
  that increase `m`.
- Construction from a raw matrix accepts stabilizers only and builds the dual
  destabilizers automatically.

## Phase convention
If `storephase=true`, the last stabilizer row stores the phase exponent `k`:
- odd prime `d`:  ω^k with k mod d
- d=2:            i^k with k mod 4

## Preset states
- `:mixed` (maximally mixed; `m=0`)
- `:product` (pure product state; `basis` is `:X`, `:Y`, `:Z`, or a vector/tuple of length `n`)
- `:ghz` (generalized GHZ on `n` qudits)

Use [`StabilizerTableau`](@ref) instead when compact storage is more important
than maintaining the dual basis. See also [`reset!`](@ref).
"""
mutable struct DestabilizerTableau{T<:InverseMod} <: AbstractTableau
    d::Int                             # qudit dimension
    n::Int                             # number of qudits
    m::Int                             # number of active generator columns (0 ≤ m ≤ n)
    stab::Matrix{Int}                 # tableau has dimensions (2n + storephase) × n
    destab::Matrix{Int}                # destabilizers: 2n × n (no phase row)
    storephase::Bool                   # whether phase information is stored
    iscanonical::Bool                  # true if the tableau is in canonical (RCEF) form
    inversemod::T                      # inverse mod function for dimension d

    # workspaces
    workspace::Matrix{Int}             # 2n×n (used by entanglement_entropy)
    generator_workspace::Vector{Int}   # length 2n + storephase

    # workspace for canonicalize!
    pivcol_of_row::Vector{Int}         # length 2n (pivot column for each row if canonical)
    xdotz_cache::Vector{Int}           # length n (stores x·z values for each generator)

    # workspace for expectation value calculations
    res_workspace::Vector{Int}         # length 2n
    c_workspace::Vector{Int}           # length n
    zacc_workspace::Vector{Int}        # length n

    # workspace for the noncommuting measurement update
    support_workspace::Vector{Int}     # length n (qudit support of one column)
end

function DestabilizerTableau(d::Int, n::Int;
    state::Symbol=:mixed,
    basis=:Z,
    storephase::Bool=true,
    inversemod::T=PrecomputedInvMod(d)
) where {T<:InverseMod}
    state_norm, basis_spec = _normalize_state_and_basis(state, basis, n)
    tab, m = _preset_tableau(d, n, state_norm, basis_spec, storephase)
    return _build_destabilizer_tableau(d, n, m, tab, storephase, inversemod;
                                       preset_state=state_norm, preset_basis=basis_spec)
end

DestabilizerTableau(d::Int, n::Int, state::Symbol; kwargs...) = DestabilizerTableau(d, n; state=state, kwargs...)

function DestabilizerTableau(d::Int, tableau::AbstractMatrix{<:Integer};
    m::Union{Int,Nothing}=nothing,
    storephase::Union{Bool,Nothing}=nothing,
    inversemod::T=PrecomputedInvMod(d),
    check::Bool=true
) where {T<:InverseMod}
    m !== nothing && m < 0 && throw(ArgumentError("m must satisfy 0 ≤ m ≤ n."))
    tab_in = (tableau isa Matrix{Int}) ? tableau : Matrix{Int}(tableau)
    layout = _infer_tableau_layout(size(tab_in, 1), size(tab_in, 2), m, storephase)
    layout === nothing && throw(ArgumentError(
        "Tableau must have shape (2n + storephase) × m or m × (2n + storephase) with m ≤ n."
    ))

    if layout.transpose
        tab_in = permutedims(tab_in)
    end

    return _build_destabilizer_tableau(d, layout.n, layout.m, tab_in, layout.storephase, inversemod;
                                      check=check)
end

function _build_destabilizer_tableau(
    d::Int,
    n::Int,
    m::Int,
    stab_in::AbstractMatrix{<:Integer},
    storephase::Bool,
    inversemod::T;
    preset_state::Union{Symbol,Nothing}=nothing,
    preset_basis=nothing,
    check::Bool=true,
) where {T<:InverseMod}
    !Primes.isprime(d) && throw(ArgumentError("Qudit dimension d must be a prime number."))
    (0 ≤ m ≤ n) || throw(ArgumentError("m must satisfy 0 ≤ m ≤ n."))
    _warn_if_dimension_unsafe(d, n)

    nrows = 2n + (storephase ? 1 : 0)
    size(stab_in, 1) == nrows || throw(ArgumentError("Tableau row count must be 2n (+1 if storephase=true)."))

    # We keep capacity n columns, but accept either n columns or m columns and pad.
    stab_in = (stab_in isa Matrix{Int}) ? stab_in : Matrix{Int}(stab_in)
    stab = if size(stab_in, 2) == n
        stab_in
    elseif size(stab_in, 2) == m
        tmp = zeros(Int, nrows, n)
        tmp[:, 1:m] .= stab_in
        tmp
    else
        throw(ArgumentError("Tableau must have either n columns (capacity) or m columns (active generators)."))
    end

    # A preset filler already writes reduced entries into a zeroed matrix, so
    # both passes below are pure overhead there -- and they are O(n^2) on a
    # matrix holding O(n) nonzeros.
    if preset_state === nothing
        # Reduce entries mod d / mod phase modulus
        @turbo for j in 1:n
            for i in 1:(2n)
                stab[i, j] = mod(stab[i, j], d)
            end
        end
        if storephase
            d_phase = phase_modulus(d)
            prow = 2n + 1
            @turbo for j in 1:n
                stab[prow, j] = mod(stab[prow, j], d_phase)
            end
        end

        # Ensure unused columns are zeroed.
        if m < n
            @turbo for j in (m+1):n, i in axes(stab, 1)
                stab[i, j] = 0
            end
        end
    end

    tab = DestabilizerTableau{T}(
        d,
        n,
        m,
        stab,
        zeros(Int, 2n, n),
        storephase,
        false,
        inversemod,
        zeros(Int, 2n, n),
        zeros(Int, nrows),
        zeros(Int, 2n),
        zeros(Int, n),
        zeros(Int, 2n),
        zeros(Int, n),
        zeros(Int, n),
        zeros(Int, n),
    )

    if preset_state === nothing
        # Before the rebuild, not after: an invalid generator set would
        # otherwise produce a dual basis that cannot satisfy duality, and the
        # failure would surface somewhere far from its cause.
        check && _validate_generators!(tab)
        rebuild_destabilizers!(tab)
        _recompute_xdotz_cache!(tab)
    else
        _preset_destabilizers!(tab, preset_state, preset_basis)
    end

    return tab
end

