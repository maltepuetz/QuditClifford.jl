# Destabilizer construction #
#############################

@inline function _pivot_columns!(
    A::AbstractMatrix{Int},
    m::Int,
    ncols::Int,
    d::Int,
    inversemod::InverseMod,
    pivots::Vector{Int},
)
    r = 1
    c = 1
    pivcount = 0
    while r <= m && c <= ncols
        pivot = r
        while pivot <= m && A[pivot, c] == 0
            pivot += 1
        end
        if pivot > m
            c += 1
            continue
        end

        if pivot != r
            @turbo for j in 1:ncols
                t = A[r, j]
                A[r, j] = A[pivot, j]
                A[pivot, j] = t
            end
        end

        # Row-strided rather than column-strided, but the contract is the same:
        # `rebuild_destabilizers!` fills `A` through `mod(..., d)`, so every
        # entry is reduced into [0, d) before this runs.
        α = inversemod(A[r, c], d)
        scale_mod!(view(A, r, c:ncols), α, d)

        for rr in (r+1):m
            β = A[rr, c]
            β == 0 && continue
            # rr >= r+1, so these are disjoint rows.
            submul_mod!(view(A, rr, c:ncols), view(A, r, c:ncols), β, d)
        end

        pivcount += 1
        pivots[pivcount] = c
        r += 1
        c += 1
    end
    return pivcount
end

function _inv_matrix_mod!(
    invA::AbstractMatrix{Int},
    Awork::AbstractMatrix{Int},
    m::Int,
    d::Int,
    inversemod::InverseMod,
)
    (size(Awork, 1) >= m && size(Awork, 2) >= m) || throw(ArgumentError("Matrix workspace too small."))
    (size(invA, 1) >= m && size(invA, 2) >= m) || throw(ArgumentError("Inverse workspace too small."))

    fill!(invA, 0)
    @inbounds for i in 1:m
        invA[i, i] = 1
    end

    for c in 1:m
        pivot = c
        while pivot <= m && Awork[pivot, c] == 0
            pivot += 1
        end
        pivot > m && throw(ArgumentError("Matrix is singular modulo d."))

        if pivot != c
            @turbo for j in 1:m
                t = Awork[c, j]
                Awork[c, j] = Awork[pivot, j]
                Awork[pivot, j] = t

                t2 = invA[c, j]
                invA[c, j] = invA[pivot, j]
                invA[pivot, j] = t2
            end
        end

        # Two matrices, so this is two passes where it used to be one fused
        # loop. Both start reduced -- `Awork` is copied from the `mod`-reduced
        # `A`, `invA` from the identity -- and at d = 2 every α is 1, which
        # `scale_mod!` skips outright.
        α = inversemod(Awork[c, c], d)
        scale_mod!(view(Awork, c, 1:m), α, d)
        scale_mod!(view(invA, c, 1:m), α, d)

        for rr in 1:m
            rr == c && continue
            β = Awork[rr, c]
            β == 0 && continue
            # rr != c (guarded above), so these are disjoint rows.
            submul_mod!(view(Awork, rr, 1:m), view(Awork, c, 1:m), β, d)
            submul_mod!(view(invA, rr, 1:m), view(invA, c, 1:m), β, d)
        end
    end

    return invA
end

function rebuild_destabilizers!(tab::DestabilizerTableau)
    n = tab.n
    m = tab.m
    d = tab.d
    stab = tab.stab
    destab = tab.destab

    fill!(destab, 0)
    m == 0 && return destab

    # These five are scratch for this call and nothing else. They used to be
    # tableau fields, which cost 6n^2 + n Ints on EVERY DestabilizerTableau --
    # about half its footprint -- to serve a function that runs at most once
    # per tableau, on the raw-matrix path alone. Presets reach
    # `_preset_destabilizers!` and never come here at all, so they were paying
    # for scratch they could not use. Locals cost one allocation on a path that
    # is already O(n^3).
    #
    # `zeros` rather than `undef`: rows m+1:n of A and Awork are never written
    # here, and this keeps them defined, as the preallocated fields did.

    # Build A = Sᵀ J (size m × 2n)
    A = zeros(Int, n, 2n)
    @inbounds for k in 1:m
        for q in 1:n
            A[k, q] = mod(stab[n+q, k], d)
            A[k, n+q] = mod(-stab[q, k], d)
        end
    end

    Awork = zeros(Int, n, 2n)
    @turbo for j in 1:(2n), i in 1:m
        Awork[i, j] = A[i, j]
    end

    pivots = zeros(Int, n)
    pivcount = _pivot_columns!(Awork, m, 2n, d, tab.inversemod, pivots)
    # If generators are not independent, destabilizers are undefined; leave destab zeroed.
    pivcount == m || return destab

    A_P = zeros(Int, n, n)
    @inbounds for j in 1:m
        pj = pivots[j]
        @turbo for i in 1:m
            A_P[i, j] = A[i, pj]
        end
    end

    @turbo for j in 1:m, i in 1:m
        Awork[i, j] = A_P[i, j]
    end

    A_inv = zeros(Int, n, n)
    _inv_matrix_mod!(A_inv, Awork, m, d, tab.inversemod)

    @inbounds for i in 1:m
        p = pivots[i]
        @turbo for j in 1:m
            destab[p, j] = mod(A_inv[i, j], d)
        end
    end
    return destab
end

"""
Fill `tab.destab` and `tab.xdotz_cache` with the closed-form duals of a preset
state, in place of the generic O(n^3) `rebuild_destabilizers!`.

Preset stabilizers are supported on a single qudit each (`:product`) or form a
chain (`:ghz`), so their duals can be written down:

  product, column j:   `:Z` -> `X_j`,  `:X` -> `Z_j^(d-1)`,  `:Y` -> `X_j`
  ghz:                 `D_1 = Z_1^(d-1)`,  `D_j = X_1...X_{j-1}` for `j >= 2`

Each satisfies the duality relation `<D_j, S_k> = delta_jk` directly. `:mixed`
has no active generators, so its dual block stays zero.
"""
function _preset_destabilizers!(tab::DestabilizerTableau, state::Symbol, basis_spec)
    n = tab.n
    d = tab.d
    destab = tab.destab
    cache = tab.xdotz_cache

    fill!(destab, 0)
    fill!(cache, 0)

    if state === :mixed
        return nothing
    elseif state === :ghz
        n == 0 && return nothing
        destab[n+1, 1] = d - 1              # D_1 = Z_1^(d-1)
        @inbounds for j in 2:n, q in 1:(j-1)
            destab[q, j] = 1                # D_j = X_1 ... X_{j-1}
        end
        return nothing                      # every GHZ generator has x.z = 0
    elseif state === :product
        @inbounds for j in 1:n
            b = _preset_basis_at(basis_spec, j)
            if b === :X
                destab[n+j, j] = d - 1      # D_j = Z_j^(d-1)
            else
                destab[j, j] = 1            # :Z and :Y both take D_j = X_j
                b === :Y && (cache[j] = 1)  # x.z = 1 only in the Y basis
            end
        end
        return nothing
    end

    throw(ArgumentError("Unknown preset state: $state."))
end

@inline _preset_basis_at(basis::Symbol, ::Int) = _canonical_basis_symbol(basis)
@inline _preset_basis_at(basis::AbstractVector{<:Symbol}, j::Int) =
    _canonical_basis_symbol(basis[j])
@inline _preset_basis_at(basis::Tuple, j::Int) = _canonical_basis_symbol(basis[j])

