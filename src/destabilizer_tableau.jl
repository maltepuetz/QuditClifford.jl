"""
    DestabilizerTableau(d::Int, n::Int; state::Symbol=:mixed, basis=:Z, storephase::Bool=true, inversemod::InverseMod=PrecomputedInvMod(d), eltype::Type, layout::Symbol=:generator)
    DestabilizerTableau(d::Int, n::Int, state::Symbol; kwargs...)
    DestabilizerTableau(d::Int, tableau::AbstractMatrix{<:Integer}; m::Union{Int,Nothing}=nothing, storephase::Union{Bool,Nothing}=nothing, inversemod::InverseMod=PrecomputedInvMod(d), check::Bool=true, eltype::Type, layout::Symbol=:generator)

Construct a destabilizer tableau for an `n`-qudit *stabilizer density operator*
(mixed-state stabilizer formalism).

This is the recommended tableau representation for most workflows. In addition
to the stabilizer generators, it maintains a dual destabilizer basis, enabling
fast span-membership tests, expectation values, and repeated measurements
without first canonicalizing the stabilizer generators.

# Arguments
- `d::Int`: Qudit dimension (must be a prime number).
- `n::Int`: Number of qudits (only for the `d, n` constructor).
- `state::Symbol`: Preset state for the positional `state` constructor.
- `tableau::AbstractMatrix{<:Integer}`: An integer stabilizer matrix in either
  `(2n + storephase) × m` or `m × (2n + storephase)` layout. The corresponding
  destabilizers are constructed automatically.
  The tableau stores a reduced copy: the caller's matrix is never modified, and
  later changes to it do not affect the tableau.

# Keyword Arguments
- `state::Symbol=:mixed`: Preset state (`:mixed`, `:product`, `:ghz`). Aliases
  `:X/:Y/:Z` map to `:product` in that basis.
- `basis=:Z`: Basis for product states (`:X`, `:Y`, `:Z`, or a per-qudit
  vector/tuple of Symbols).
- `storephase::Bool=true`: Whether to store the stabilizer generator phases (for
  the `(d, n)` constructor). When constructing from a `tableau`, `storephase` is
  inferred from the matrix shape if not provided. Destabilizers never carry a
  phase.
- `m::Union{Int,Nothing}=nothing`: Number of active stabilizer-generator columns
  (for the `(d, tableau)` constructor).
- `inversemod::InverseMod=PrecomputedInvMod(d)`: Inversion strategy used for
  phase calculations and construction of the dual basis.
  A `PrecomputedInvMod` must be built for this `d`; a table of another length
  throws.
- `check::Bool=true`: For the `(d, tableau)` constructor only, verify that the
  supplied generators commute and are independent, and at `d = 2` with a phase
  row that each is Hermitian (phase exponent `≡ x·z mod 2`), throwing
  `ArgumentError` naming the offending generator, pair or rank if not. The
  preset constructors satisfy all of this by construction and take no such
  keyword. `check=false` skips an
  `O(n^3)` validation and builds the tableau regardless -- every later operation
  then rests on a contract that may not hold, and `is_pure` will call such a
  tableau pure; `is_pure(tab; verify=true)` is what sees through it.
- `eltype::Type`: Element type of the stored X and Z exponents of the
  stabilizers and destabilizers: `UInt8` for `d ≤ 251`, `UInt16` for
  `d ≤ 65521`, or `Int` for every `d`. The default is the narrowest of these
  that holds `d`. Another type, or one too narrow for `d`, throws an
  `ArgumentError`. The choice affects memory and speed only:
  every result, and every matrix the tableau returns, is the same `Int` value
  in each element type. Phases are always stored as `Int`.
- `layout::Symbol=:generator`: Storage layout of the X and Z blocks of the
  stabilizers and destabilizers: `:generator` (generator `j` in column `j`) or
  `:qudit` (generator `j` in row `j`); any other symbol throws an
  `ArgumentError`. It affects speed only and is independent of the orientation
  of a raw `tableau` matrix, which is inferred from its shape either way. See
  [`qudit_major!`](@ref), [`generator_major!`](@ref) and
  [`tableau_layout`](@ref).

# Examples
```jldoctest
julia> tab = DestabilizerTableau(2, 3; state = :mixed);

julia> tab.m, is_pure(tab)
(0, false)

julia> tab = DestabilizerTableau(2, 3; state = :product, basis = :X);

julia> tab.m, is_pure(tab)
(3, true)

julia> raw = reshape([0, 1, 0], 3, 1);   # one qubit, generator Z, phase exponent 0

julia> DestabilizerTableau(2, raw) == DestabilizerTableau(2, 1; state = :product, basis = :Z)
true
```

# Notes
## Representation
The represented abelian stabilizer subgroup `S` is generated by `m` independent
commuting Paulis (`0 ≤ m ≤ n`). Both properties are contract: the raw-matrix
constructor enforces them (see `check`), the presets satisfy them by
construction, and `measure!` and [`canonicalize!`](@ref) preserve them. That is
what lets [`is_pure`](@ref) decide on `m == n` alone. Each active stabilizer `S_j` has a destabilizer
`D_j` satisfying the duality relation `⟨D_j, S_k⟩ = δ_jk` modulo `d`.

The stabilizers are stored as `n × n` blocks of X and Z exponents and a phase
vector, the destabilizers as `n × n` X and Z blocks without phases.
[`stabilizer_matrix`](@ref) returns the stabilizers stacked as a
`(2n + storephase) × n` matrix, [`destabilizer_matrix`](@ref) the
destabilizers as a `2n × n` one.
- Only the **first `m` columns** are active stabilizer/destabilizer pairs.
- Columns `m+1:n` are unused (kept zero) and provide capacity for measurements
  that increase `m`.
- Construction from a raw matrix accepts stabilizers only and builds the dual
  destabilizers automatically.

## Phase convention
If `storephase=true`, the phase vector stores the phase exponent `k` of each stabilizer:
- odd prime `d`:  ω^k with k mod d
- d=2:            i^k with k mod 4

## Preset states
- `:mixed` (maximally mixed; `m=0`)
- `:product` (pure product state; `basis` is `:X`, `:Y`, `:Z`, or a vector/tuple of length `n`)
- `:ghz` (generalized GHZ on `n` qudits)

Use [`StabilizerTableau`](@ref) instead when compact storage is more important
than maintaining the dual basis. See also [`reset!`](@ref).
"""
mutable struct DestabilizerTableau{IM<:InverseMod, E<:_StorageEltype} <: AbstractTableau
    d::Int                             # qudit dimension
    n::Int                             # number of qudits
    m::Int                             # number of active generator columns (0 ≤ m ≤ n)
    stab_x::_BlockMatrix{E}            # n×n X exponents, one generator per column or row (see layout, _padded_block)
    stab_z::_BlockMatrix{E}            # n×n Z exponents, laid out as stab_x
    phase::Vector{Int}                 # phase exponent of generator j; length n, or 0 without storephase
    destab_x::_BlockMatrix{E}          # n×n X exponents of the destabilizers (no phases), laid out as stab_x
    destab_z::_BlockMatrix{E}          # n×n Z exponents of the destabilizers, laid out as stab_x
    storephase::Bool                   # whether phase information is stored
    iscanonical::Bool                  # true if the tableau is in canonical (RCEF) form
    layout::Union{GeneratorMajor, QuditMajor}  # GeneratorMajor: generator j in column j; QuditMajor: in row j
    inversemod::IM                     # inverse mod function for dimension d

    # workspaces
    generator_workspace::Vector{Int}   # length 2n + storephase
    pivot_workspace::Vector{E}         # length 2n, [x; z] of a pivot or new destabilizer (no phase)

    # workspace for canonicalize!
    pivcol_of_row::Vector{Int}         # length 2n (pivot column for each row if canonical)
    xdotz_cache::Vector{Int}           # length n (stores x·z values for each generator)

    # workspace for expectation value calculations
    res_workspace::Vector{Int}         # length 2n
    c_workspace::Vector{Int}           # length n
    zacc_workspace::Vector{Int}        # length n

    # workspace for the noncommuting measurement update
    support_workspace::Vector{Int}     # length n (qudit support of one column)

    # rank elimination and commutation-check workspaces (see src/rank_workspaces.jl)
    rank_workspace::Matrix{E}          # 2n×n for d ≥ 3, else 0×0
    bit_workspace::Matrix{UInt64}      # (cld(2n, 64) + 2)×n for d = 2, else 0×0
end

Base.@constprop :aggressive function DestabilizerTableau(d::Int, n::Int;
    state::Symbol=:mixed,
    basis=:Z,
    storephase::Bool=true,
    inversemod::T=PrecomputedInvMod(d),
    eltype::Type{E}=_default_eltype(d),
    layout::Symbol=:generator,
) where {T<:InverseMod, E}
    _check_eltype(eltype, d)
    _check_layout(layout)
    state_norm, basis_spec = _normalize_state_and_basis(state, basis, n)
    b, phase, m = _preset_tableau(eltype, d, n, state_norm, basis_spec, storephase)
    tab = _build_destabilizer_tableau(eltype, d, n, m, (b, phase), storephase, inversemod;
                                      preset_state=state_norm, preset_basis=basis_spec)
    return _apply_layout!(tab, layout)
end

DestabilizerTableau(d::Int, n::Int, state::Symbol; kwargs...) = DestabilizerTableau(d, n; state=state, kwargs...)

Base.@constprop :aggressive function DestabilizerTableau(d::Int, tableau::AbstractMatrix{<:Integer};
    m::Union{Int,Nothing}=nothing,
    storephase::Union{Bool,Nothing}=nothing,
    inversemod::T=PrecomputedInvMod(d),
    check::Bool=true,
    eltype::Type{E}=_default_eltype(d),
    layout::Symbol=:generator,
) where {T<:InverseMod, E}
    _check_eltype(eltype, d)
    _check_layout(layout)
    m !== nothing && m < 0 && throw(ArgumentError("m must satisfy 0 ≤ m ≤ n."))
    shape = _infer_tableau_layout(size(tableau, 1), size(tableau, 2), m, storephase)
    shape === nothing && throw(ArgumentError(
        "Tableau must have shape (2n + storephase) × m or m × (2n + storephase) with m ≤ n."
    ))

    # The build step copies the generators into the tableau's own arrays and
    # never writes to its input.
    tab_in = shape.transpose ? permutedims(tableau) : tableau

    tab = _build_destabilizer_tableau(eltype, d, shape.n, shape.m, tab_in, shape.storephase,
                                      inversemod; check=check)
    return _apply_layout!(tab, layout)
end

function _build_destabilizer_tableau(
    ::Type{E},
    d::Int,
    n::Int,
    m::Int,
    stab_in,
    storephase::Bool,
    inversemod::T;
    preset_state::Union{Symbol,Nothing}=nothing,
    preset_basis=nothing,
    check::Bool=true,
) where {E<:_StorageEltype, T<:InverseMod}
    !Primes.isprime(d) && throw(ArgumentError("Qudit dimension d must be a prime number."))
    _check_inversemod(inversemod, d)
    (0 ≤ m ≤ n) || throw(ArgumentError("m must satisfy 0 ≤ m ≤ n."))
    _warn_if_dimension_unsafe(d, n)

    b, phase = _generator_storage(stab_in, E, d, n, m, storephase)

    tab = DestabilizerTableau{T, E}(
        d,
        n,
        m,
        b.x,
        b.z,
        phase,
        _destab_blocks(E, n)...,
        storephase,
        false,
        GeneratorMajor(),
        inversemod,
        zeros(Int, 2n + (storephase ? 1 : 0)),
        zeros(E, 2n),
        zeros(Int, 2n),
        zeros(Int, n),
        zeros(Int, 2n),
        zeros(Int, n),
        zeros(Int, n),
        zeros(Int, n),
        _storage_rank_workspace(E, d, n),
        _bit_rank_workspace(d, n),
    )

    return _init_destabilizers!(tab, _layout_marker(tab), preset_state, preset_basis, check)
end

# Fill the destabilizers and `xdotz_cache` of a new tableau: the closed-form
# duals of a preset, or the duals of validated raw generators.
function _init_destabilizers!(tab::DestabilizerTableau, L::TableauLayout,
                              preset_state::Union{Symbol,Nothing}, preset_basis, check::Bool)
    if preset_state === nothing
        # Before the rebuild, not after: an invalid generator set would
        # otherwise produce a dual basis that cannot satisfy duality, and the
        # failure would surface somewhere far from its cause.
        check && _validate_generators!(tab, L)
        rebuild_destabilizers!(tab, L)
        _recompute_xdotz_cache!(tab, L)
    else
        _preset_destabilizers!(tab, L, preset_state, preset_basis)
    end

    return tab
end

